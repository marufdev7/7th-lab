# Experiment name:   Write a program for finding the largest and smallest element in a given list.
# Source Code:

numbers = [20, 25, 7, 40, 56]
largest = max(numbers)
smallest = min(numbers)
print("Largest Element =", largest)
print("Smallest Element =", smallest)


# Output
# Largest Element = 56
# Smallest Element = 7